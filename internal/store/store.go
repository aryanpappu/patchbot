// Package store persists runs, approval history, and replayable events.
// Callers must redact secrets before passing text or JSON to the store.
package store

import (
	"context"
	"encoding/json"
	"errors"
	"time"
)

// Status describes a run's lifecycle, independently of its current phase.
type Status string

// Run statuses. Every active status holds the unique slot for its issue.
const (
	StatusQueued           Status = "queued"
	StatusRunning          Status = "running"
	StatusNeedsInfo        Status = "needs_info"
	StatusAwaitingApproval Status = "awaiting_approval"
	StatusApproved         Status = "approved"
	StatusSucceeded        Status = "succeeded"
	StatusFailed           Status = "failed"
	StatusCancelled        Status = "cancelled"
	StatusRejected         Status = "rejected"
)

// IsActive reports whether the run holds its issue's active-run slot.
func (s Status) IsActive() bool {
	switch s {
	case StatusQueued, StatusRunning, StatusNeedsInfo, StatusAwaitingApproval, StatusApproved:
		return true
	default:
		return false
	}
}

// Phase identifies the work being performed within a run.
type Phase string

// Run phases, as defined by the merged plan.
const (
	PhasePreflight Phase = "preflight"
	PhaseRefine    Phase = "refine"
	PhaseClone     Phase = "clone"
	PhaseBaseline  Phase = "baseline"
	PhaseCode      Phase = "code"
	PhaseVerify    Phase = "verify"
	PhasePublish   Phase = "publish"
)

// Store errors are suitable for errors.Is, including when wrapped with context.
var (
	ErrNotFound        = errors.New("not found")
	ErrActiveRunExists = errors.New("an active run already exists for this issue")
	ErrConflict        = errors.New("run or spec is not in the expected state")
)

// Run is a durable run row. IDs are generated by the store. Optional numeric
// values and times use pointers: nil means unknown, including unpriced cost.
// All times round-trip at UTC millisecond precision; all money is micro-USD.
// Generation advances on lifecycle changes and operator spec edits. Workers
// retain their own generation to prevent stale transitions, including ABA.
type Run struct {
	ID               int64           `json:"id"`
	Generation       int64           `json:"generation"`
	Repo             string          `json:"repo"`
	IssueNumber      int64           `json:"issue_number"`
	IssueTitle       string          `json:"issue_title"`
	Mode             string          `json:"mode"`
	RetryOf          *int64          `json:"retry_of"`
	Trigger          string          `json:"trigger"`
	Provider         string          `json:"provider"`
	RefineModel      string          `json:"refine_model"`
	CodeModel        string          `json:"code_model"`
	DryRun           bool            `json:"dry_run"`
	Status           Status          `json:"status"`
	Phase            Phase           `json:"phase"`
	Outcome          string          `json:"outcome"`
	BaseSHA          string          `json:"base_sha"`
	HeadSHA          string          `json:"head_sha"`
	Branch           string          `json:"branch"`
	PRNumber         *int64          `json:"pr_number"`
	PRURL            string          `json:"prurl"`
	PRDraft          bool            `json:"pr_draft"`
	Summary          string          `json:"summary"`
	TestsStatus      string          `json:"tests_status"`
	TestAttempts     int64           `json:"test_attempts"`
	Turns            int64           `json:"turns"`
	InputTokens      *int64          `json:"input_tokens"`
	OutputTokens     *int64          `json:"output_tokens"`
	CacheReadTokens  *int64          `json:"cache_read_tokens"`
	CacheWriteTokens *int64          `json:"cache_write_tokens"`
	CostMicros       *int64          `json:"cost_micros"`
	LimitsJSON       json.RawMessage `json:"limits_json"`
	ErrorKind        string          `json:"error_kind"`
	ErrorMessage     string          `json:"error_message"`
	CreatedAt        time.Time       `json:"created_at"`
	UpdatedAt        time.Time       `json:"updated_at"`
	StartedAt        *time.Time      `json:"started_at"`
	FinishedAt       *time.Time      `json:"finished_at"`
	HeartbeatAt      *time.Time      `json:"heartbeat_at"`
	WaitingSince     *time.Time      `json:"waiting_since"`
}

// RunFilter selects runs in descending (created_at, id) order. Limit defaults
// to 50 and is capped at 500. Cursor is an opaque NextCursor from a prior page;
// use the same filters throughout pagination.
type RunFilter struct {
	Repo        string
	IssueNumber int64
	Statuses    []Status
	Limit       int
	Cursor      string
}

// RunPage contains runs and a continuation cursor, empty on the final page.
type RunPage struct {
	Runs       []Run  `json:"runs"`
	NextCursor string `json:"next_cursor"`
}

// RunPatch changes status-related metadata along with the phase. Nil fields
// leave existing values alone. The store manages lifecycle timestamps and emits
// run.status in the same transaction. Same-status transitions can change phase.
// ExpectedGeneration, when set, also guards ownership of the source snapshot.
type RunPatch struct {
	ExpectedGeneration       *int64
	Phase                    Phase
	IssueTitle               *string
	Outcome                  *string
	ErrorKind, ErrorMessage  *string
	BaseSHA, HeadSHA, Branch *string
	PRNumber                 *int64
	PRURL                    *string
	PRDraft                  *bool
	Summary, TestsStatus     *string
}

// Spec is an immutable version. Hash is the SHA-256 of the caller's canonical
// spec representation (which may contain structured fields beyond BodyMD).
// SaveSpec assigns Version when zero, otherwise requires the next version.
type Spec struct {
	RunID     int64     `json:"run_id"`
	Version   int64     `json:"version"`
	BodyMD    string    `json:"body_md"`
	Hash      string    `json:"hash"`
	IssueHash string    `json:"issue_hash"`
	Source    string    `json:"source"`
	Notes     string    `json:"notes"`
	CommentID *int64    `json:"comment_id"`
	CreatedAt time.Time `json:"created_at"`
}

// SpecEdit guards both the source lifecycle snapshot and the prior spec. The
// new spec, waiting status, status event and edit action are one transaction.
type SpecEdit struct {
	Spec                     Spec
	From, To                 Status
	Generation, PriorVersion int64
	PriorHash, Actor         string
}

// Approval binds a decision (approve/revise/reject) to an exact spec version
// and hash. Channel is ui/cli/github. The newest decision for a spec wins.
type Approval struct {
	ID          int64     `json:"id"`
	RunID       int64     `json:"run_id"`
	SpecVersion int64     `json:"spec_version"`
	SpecHash    string    `json:"spec_hash"`
	Decision    string    `json:"decision"`
	Actor       string    `json:"actor"`
	Channel     string    `json:"channel"`
	CreatedAt   time.Time `json:"created_at"`
}

// Question stores a question and, optionally, its answer and provenance.
type Question struct {
	ID, RunID                         int64
	Body                              string
	Answer, AnsweredBy, AnswerChannel *string
	CommentID                         *int64
	CreatedAt                         time.Time
	AnsweredAt                        *time.Time
}

// Step is a structured execution record, separate from the SSE event log.
// Seq is allocated per run when zero; a nonzero value updates that step.
// A completed llm step's usage is included in the run totals atomically.
type Step struct {
	RunID            int64      `json:"run_id"`
	Seq              int64      `json:"seq"`
	Phase            Phase      `json:"phase"`
	Kind             string     `json:"kind"`
	Tool             string     `json:"tool"`
	Status           string     `json:"status"`
	Turn             *int64     `json:"turn"`
	InputJSON        string     `json:"input_json"`
	OutputText       string     `json:"output_text"`
	StopReason       string     `json:"stop_reason"`
	InputTokens      *int64     `json:"input_tokens"`
	OutputTokens     *int64     `json:"output_tokens"`
	CacheReadTokens  *int64     `json:"cache_read_tokens"`
	CacheWriteTokens *int64     `json:"cache_write_tokens"`
	CostMicros       *int64     `json:"cost_micros"`
	ExitCode         *int64     `json:"exit_code"`
	DurationMS       *int64     `json:"duration_ms"`
	StartedAt        time.Time  `json:"started_at"`
	FinishedAt       *time.Time `json:"finished_at"`
}

// Event is a replayable event. AppendEvent assigns Seq and defaults CreatedAt.
type Event struct {
	RunID       int64           `json:"run_id"`
	Seq         int64           `json:"seq"`
	Type        string          `json:"type"`
	PayloadJSON json.RawMessage `json:"payload_json"`
	CreatedAt   time.Time       `json:"created_at"`
}

// Artifact stores a redacted artifact for one kind and test attempt.
// Callers cap content at its source before saving it.
type Artifact struct {
	RunID     int64
	Kind      string
	Attempt   int64
	Content   string
	CreatedAt time.Time
}

// Action audits a UI, CLI, or GitHub action. Kind is start/edit_spec/approve/
// revise/reject/cancel/retry/answer; details are redacted JSON.
type Action struct {
	ID, RunID   int64
	Kind, Actor string
	Channel     string
	PayloadJSON json.RawMessage
	CreatedAt   time.Time
}

// Store is the persistence boundary used by the runner and server. Each method
// is atomic and never executes a caller-controlled callback in a transaction.
// Policy (allowed transitions, actor authorization, issue freshness, expiry,
// and revision limits) belongs to the runner; this layer enforces CAS and the
// latest-spec approval binding. Missing reads return ErrNotFound.
type Store interface {
	CreateRun(context.Context, Run) (Run, error)
	GetRun(context.Context, int64) (Run, error)
	ListRuns(context.Context, RunFilter) (RunPage, error)
	SetRunStatus(ctx context.Context, id int64, from, to Status, patch RunPatch) error
	Heartbeat(context.Context, int64) error
	FailStaleRuns(ctx context.Context, olderThan time.Time) (int64, error)

	RecordStep(context.Context, Step) (Step, error)
	ListSteps(ctx context.Context, runID int64) ([]Step, error)
	AppendEvent(context.Context, Event) (int64, error)
	EventsAfter(ctx context.Context, runID, afterSeq int64, limit int) ([]Event, error)

	SaveSpec(context.Context, Spec) (Spec, error)
	EditSpec(context.Context, SpecEdit) (Spec, error)
	LatestSpec(ctx context.Context, runID int64) (Spec, error)
	ListSpecs(context.Context, int64) ([]Spec, error)
	ListApprovals(context.Context, int64) ([]Approval, error)
	ListArtifacts(context.Context, int64) ([]ArtifactMetadata, error)
	RecordApproval(context.Context, Approval) (Approval, error)
	// DecideRun atomically binds a decision to the expected latest version/hash,
	// CASes status and generation, and appends its status event and action audit.
	// An optional phase atomically claims approved asynchronous execution.
	DecideRun(context.Context, Status, Status, Approval, int64, ...Phase) error
	// StartCode claims approved work only while the exact latest approval still
	// matches and the worker still owns generation. SaveSpec refuses edits after
	// this atomic claim.
	StartCode(ctx context.Context, runID, version int64, hash string, generation int64) error
	// SetSpecComment attaches publication provenance without editing spec content.
	SetSpecComment(ctx context.Context, runID, version int64, hash string, commentID int64) error
	ValidApproval(ctx context.Context, runID, specVersion int64, specHash string) (Approval, error)
	SaveQuestion(context.Context, Question) (Question, error)
	ListQuestions(ctx context.Context, runID int64) ([]Question, error)

	RecordAction(context.Context, Action) (Action, error)
	ListActions(ctx context.Context, runID int64) ([]Action, error)
	SaveArtifact(context.Context, Artifact) error
	GetArtifact(ctx context.Context, runID int64, kind string, attempt int64) (Artifact, error)
	Close() error
}

// IsSchemaIdentifier reports fixed phase/status values owned by the harness.
// Redaction boundaries preserve these enums while still masking arbitrary text.
func IsSchemaIdentifier(key, value string) bool {
	switch key {
	case "phase":
		switch Phase(value) {
		case PhasePreflight, PhaseRefine, PhaseClone, PhaseBaseline, PhaseCode, PhaseVerify, PhasePublish:
			return true
		}
	case "status":
		switch Status(value) {
		case StatusQueued, StatusRunning, StatusNeedsInfo, StatusAwaitingApproval, StatusApproved, StatusSucceeded, StatusFailed, StatusCancelled, StatusRejected:
			return true
		}
		return value == "ok" || value == "error"
	}
	return false
}
